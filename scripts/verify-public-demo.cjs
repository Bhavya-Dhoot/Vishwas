const assert = require('node:assert/strict');
const { mkdir, writeFile } = require('node:fs/promises');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const url = process.env.DEMO_URL || 'https://vishwas-care-demo.vercel.app';
  const browser = await chromium.launch({ headless: true, ...(process.env.BROWSER_EXECUTABLE ? { executablePath: process.env.BROWSER_EXECUTABLE } : {}) });
  const errors = [];
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  page.setDefaultTimeout(15000);
  const action = async locator => {
    const pending = page.waitForResponse(response => response.url() === `${url}/api/actions`);
    await locator.click();
    const response = await pending;
    assert.equal(response.status(), 200, await response.text());
    return response.json();
  };
  try {
    await page.goto(url);
    await page.getByText(/Temporary demo/).waitFor();
    const intake = page.locator('[data-form=pre_arrival]');
    await intake.locator('[name=name]').fill('Public Demo Visitor');
    await intake.locator('[name=language]').selectOption('Hindi');
    await intake.locator('[name=departmentId]').selectOption('endocrinology');
    await intake.locator('[name=contactConsent]').check();
    await intake.locator('[name=scheduleConsent]').check();
    const createdResponse = page.waitForResponse(response => response.url().endsWith('/api/session/patient'));
    await intake.locator('button[type=submit]').click();
    const response = await createdResponse;
    assert.equal(response.status(), 200, await response.text());
    const created = await response.json();
    const { patientId, episodeId } = created.result;
    assert.equal(created.result.status, 'department_inquiry');
    await page.getByRole('heading', { name: 'Public Demo Visitor', exact: true }).waitFor();
    assert.equal(await page.locator('input[type=file]').count(), 0);
    const patientState = await (await page.request.get(`${url}/api/state`)).json();
    assert.equal(patientState.patients.length, 1);
    assert.equal(patientState.audit, undefined);
    const disabledUpload = await page.request.post(`${url}/api/documents`, { headers: { Origin: url }, data: {} });
    assert.equal(disabledUpload.status(), 403);
    const forbiddenOrigin = await page.request.post(`${url}/api/session/demo`, { headers: { Origin: 'https://example.org' }, data: { role: 'staff' } });
    assert.equal(forbiddenOrigin.status(), 403);
    const staff = await page.request.post(`${url}/api/session/demo`, { headers: { Origin: url }, data: { role: 'staff' } });
    assert.equal(staff.status(), 200, await staff.text());
    await page.reload();
    await page.locator(`[data-patient="${patientId}"]`).first().click();
    let current = await action(page.locator(`[data-accept="${episodeId}"]`).first());
    assert.equal(current.episodes.find(e => e.id === episodeId).status, 'booked');
    for (const id of ['referral', 'reports', 'appointment']) await action(page.locator(`[data-document="${id}"]`));
    await action(page.getByRole('button', { name: 'Record check-in', exact: true }));
    const complete = page.locator('form[data-form=complete_visit]');
    await complete.locator('[name=followUpDate]').fill('2026-10-06');
    await complete.locator('[name=evidence]').fill('Fictional public demo attendance.');
    current = await action(complete.getByRole('button', { name: /Confirm visit complete/ }));
    const followId = current.result.episodeId;
    await page.locator('[data-command=demo-tools]').click();
    await page.locator('#demo-date').fill('2026-10-07');
    await action(page.locator('[data-command=set-date]'));
    await page.locator('nav [data-nav=inbox]').click();
    current = await action(page.getByRole('button', { name: 'Run reminders', exact: true }));
    assert.ok(current.messages.some(m => m.episodeId === followId && m.kind === 'reminder'));
    const reply = page.locator('form[data-form=patient_reply]');
    await reply.locator('[name=barrier]').selectOption('travel');
    await reply.locator('[name=text]').fill('Fictional transport delay.');
    await action(reply.getByRole('button', { name: 'Add simulated patient reply' }));
    await action(page.locator('[data-enhance]').first());
    await action(page.locator('[data-approve]').first());
    const resolution = page.locator('form[data-form=resolve_barrier]');
    await resolution.locator('[name=note]').fill('Fictional transport arranged.');
    await action(resolution.getByRole('button', { name: 'Log resolution' }));
    await page.locator('nav [data-nav=journeys]').click();
    await action(page.locator(`[data-accept="${followId}"]`).first());
    await action(page.getByRole('button', { name: 'Record check-in', exact: true }));
    const returned = page.locator('form[data-form=complete_visit]');
    await returned.locator('[name=evidence]').fill('Fictional public demo return.');
    current = await action(returned.getByRole('button', { name: /Confirm visit complete/ }));
    assert.equal(current.episodes.find(e => e.id === followId).status, 'completed');
    const other = await browser.newPage();
    await other.goto(url);
    await other.locator('[data-command=demo-staff]').click();
    await other.getByRole('heading', { name: 'Good care, kept on track.' }).waitFor();
    const otherState = await (await other.request.get(`${url}/api/state`)).json();
    assert.ok(!otherState.patients.some(p => p.id === patientId), 'Visitor isolation');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await mkdir('test-results', { recursive: true });
    await page.screenshot({ path: 'test-results/public-demo-mobile.png', fullPage: true });
    const pdf = await page.request.get(`${url}/Vishwas-Supporting-Document.pdf`);
    assert.equal(pdf.status(), 200);
    assert.equal((await pdf.body()).subarray(0, 5).toString(), '%PDF-');
    assert.deepEqual(errors, []);
    const result = { passed: true, url, checkedAt: new Date().toISOString(), data: 'fictional', checks: ['home enquiry', 'department routing', 'one-acceptance booking', 'recorded attendance', 'follow-up reminder', 'barrier and reviewed reply', 'confirmed return', 'visitor isolation', 'patient scoping', 'cross-origin rejection', 'uploads disabled', '390px layout', 'public PDF'], browserErrors: errors };
    await writeFile('docs/public-demo-proof.json', JSON.stringify(result, null, 2) + '\n');
    console.log(JSON.stringify(result, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
